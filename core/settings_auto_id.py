def apply_client_auto_id(panel: str, base_auto_id: dict, base_radio_names: dict | None = None,
                         client_id: str = "") -> dict:
    """把客户端专属覆盖合并进 base_auto_id，返回合并后的 AUTO_ID（原地修改）。

    同时把 RADIO_NAMES 覆盖合并进 base_radio_names（若提供）。
    仅当 client_id 命中且存在该面板的覆盖时才合并。
    """
    if not client_id or client_id != "guangfa":
        return base_auto_id
    overrides = GUANGFA_AUTO_ID.get(panel)
    if not overrides:
        return base_auto_id
    base_auto_id.update(overrides.get("AUTO_ID", {}))
    if base_radio_names is not None:
        base_radio_names.update(overrides.get("RADIO_NAMES", {}))
    return base_auto_id
